"""Generates src/FancyZonesClone.Core/Overlay/InterDigits.g.cs from Inter's variable font.

To regenerate, install fontTools, download Inter[opsz,wght].ttf from
https://github.com/google/fonts/tree/main/ofl/inter, and run:

    python eng/generate-digit-outlines.py "path/to/Inter[opsz,wght].ttf"

The script instances the font at WEIGHT and OPTICAL_SIZE, then flattens the digits' quadratic outlines into
polygons. Coordinates are in cap heights, with y down from the cap line, so a digit is about 1 tall.
"""

import math
import pathlib
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WEIGHT = 600
OPTICAL_SIZE = 32

# Largest distance between a curve and its chords, in cap heights. At 0.001, a 500px digit is off by half a pixel.
TOLERANCE = 0.001

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "src/FancyZonesClone.Core/Overlay/InterDigits.g.cs"
DIGIT_NAMES = "0123456789"


class FlattenPen(BasePen):
    """Collects each contour as a list of points, splitting curves into chords within a tolerance."""

    def __init__(self, glyph_set, tolerance):
        super().__init__(glyph_set)
        self.tolerance = tolerance
        self.contours = []
        self.current = None

    def _moveTo(self, pt):
        self.current = [pt]

    def _lineTo(self, pt):
        self.current.append(pt)

    def _qCurveToOne(self, pt1, pt2):
        p0 = self._getCurrentPoint()
        deviation = math.dist((0, 0), (p0[0] - 2 * pt1[0] + pt2[0], p0[1] - 2 * pt1[1] + pt2[1])) / 4
        for t in self._steps(deviation):
            u = 1 - t
            self.current.append((u * u * p0[0] + 2 * u * t * pt1[0] + t * t * pt2[0], u * u * p0[1] + 2 * u * t * pt1[1] + t * t * pt2[1]))

    def _curveToOne(self, pt1, pt2, pt3):
        p0 = self._getCurrentPoint()
        deviation = 0.75 * max(
            math.dist((0, 0), (p0[0] - 2 * pt1[0] + pt2[0], p0[1] - 2 * pt1[1] + pt2[1])),
            math.dist((0, 0), (pt1[0] - 2 * pt2[0] + pt3[0], pt1[1] - 2 * pt2[1] + pt3[1])))
        for t in self._steps(deviation):
            u = 1 - t
            self.current.append(tuple(
                u ** 3 * a + 3 * u * u * t * b + 3 * u * t * t * c + t ** 3 * d for a, b, c, d in zip(p0, pt1, pt2, pt3)))

    def _closePath(self):
        if len(self.current) > 1 and self.current[-1] == self.current[0]:
            self.current.pop()
        self.contours.append(self.current)
        self.current = None

    _endPath = _closePath

    def _steps(self, deviation):
        count = max(1, math.ceil(math.sqrt(deviation / self.tolerance)))
        return [i / count for i in range(1, count + 1)]


def number(value):
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return ("0" if text in ("", "-0") else text) + "f"


def main(font_path):
    font = instantiateVariableFont(TTFont(font_path), {"wght": WEIGHT, "opsz": OPTICAL_SIZE})
    cap = font["OS/2"].sCapHeight
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    version = font["name"].getDebugName(5)

    lines = [
        "// <auto-generated>",
        f"// Generated by eng/generate-digit-outlines.py from Inter {version}, weight {WEIGHT}, optical size {OPTICAL_SIZE}.",
        "// Inter is licensed under the SIL Open Font License 1.1. See THIRD-PARTY-NOTICES.md. Don't edit this file.",
        "// </auto-generated>",
        "",
        "namespace FancyZonesClone.Core.Overlay;",
        "",
        "internal static partial class InterDigits",
        "{",
        "    private static readonly DigitGlyph[] _glyphs =",
        "    [",
    ]

    for digit in DIGIT_NAMES:
        name = cmap[ord(digit)]
        pen = FlattenPen(glyph_set, TOLERANCE * cap)
        glyph_set[name].draw(pen)
        contours = [[(x / cap, (cap - y) / cap) for x, y in contour] for contour in pen.contours]
        xs = [x for contour in contours for x, _ in contour]
        advance = glyph_set[name].width / cap

        lines.append(f"        // {digit}: {len(contours)} contours, {sum(map(len, contours))} points.")
        lines.append(f"        new({number(advance)}, {number(min(xs))}, {number(max(xs))},")
        lines.append("        [")
        for contour in contours:
            flat = [number(v) for point in contour for v in point]
            lines.append("            [")
            for start in range(0, len(flat), 16):
                lines.append("                " + ", ".join(flat[start:start + 16]) + ",")
            lines.append("            ],")
        lines.append("        ]),")

    lines += ["    ];", "}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main(sys.argv[1])
